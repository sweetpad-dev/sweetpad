//! File types by extension, and which types hold text, transcribed from the
//! `FileType` specs in Xcode 27's `*.xcspec` files: extensions lowercased,
//! the first spec to claim one winning, text-ness inherited through
//! `BasedOn`. Xcode types a file in a synchronized folder by its UTI, which
//! the specs only partly cover; `sdef`, `xcprivacy` and `opml` are `text.xml`
//! by what `xcodebuild -dumpPIF` printed for them.

/// The Xcode file type for a file extension, in any case.
pub(crate) fn for_extension(extension: &str) -> Option<&'static str> {
    let lower = extension.to_ascii_lowercase();
    EXTENSIONS
        .binary_search_by(|(e, _)| (*e).cmp(lower.as_str()))
        .ok()
        .map(|i| EXTENSIONS[i].1)
}

/// Whether a file type holds text, which is when Xcode reports a file's
/// text encoding.
pub(crate) fn is_text(file_type: &str) -> bool {
    TEXT_TYPES.binary_search(&file_type).is_ok()
}

